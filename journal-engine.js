function renderJournal(){

    const container = document.getElementById("journal");

    if(!container) return;

    let html = "";

    jurnal.forEach(item => {

        html += `

        <section class="card journal-card">

            <h2>${item.title}</h2>

            ${item.content}

        </section>

        `;

    });

    container.innerHTML = html;

}

