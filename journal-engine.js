function renderJournal() {

    let container =
        document.getElementById("journal") ||
        document.getElementById("isiJurnal") ||
        document.getElementById("narasi");

    // Jika container tidak ditemukan,
    // buat otomatis agar jurnal tetap muncul.
    if (!container) {

        container = document.createElement("div");

        container.id = "journal";

        document.body.appendChild(container);

        console.warn(
            "Container Liga Jurnal tidak ditemukan. Container otomatis dibuat."
        );
    }

    // Bersihkan isi lama.
    container.innerHTML = "";

    // Render seluruh jurnal.
    jurnal.forEach(function(item) {

        const article =
            document.createElement("section");

        article.className =
            "card journal-card";

        article.innerHTML = `
            <h2>${item.title}</h2>
            ${item.content}
        `;

        container.appendChild(article);

    });

    console.log(
        "Liga Jurnal berhasil dirender:",
        jurnal.length,
        "artikel."
    );
}


